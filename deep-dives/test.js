'use strict';
const assert = require('node:assert/strict');
const s = require('./study.js');
assert.deepEqual(s.queue(100, 30, 2, 5), {demand:30, capacity:24, utilization:1.25, backlog:6});
assert.equal(s.queue(80, 25, 2, 3).backlog, 0);
assert.equal(s.queue(0, 0, 1, 1).utilization, 0);
assert.equal(s.queue(100, 20, 1e308, 0.1), null);
for (const values of [[NaN,20,2,3], [100,-1,2,3], [100,101,2,3], [100,20,0,3], [100,20,1.5,3], [100,20,1,0]]) assert.equal(s.queue(...values), null);
const budget = s.budget(100000, 99.5, 600);
assert.equal(budget.allowed, 500);
assert.equal(budget.remaining, -100);
assert.equal(budget.burn, 1.2);
assert.equal(budget.observed, 99.4);
assert.ok(Math.abs(s.budget(10000, 99.9, 10).remaining) < 1e-9);
for (const values of [[0,99,0], [100,100,0], [100,0,0], [100,99,101], [100,99,1.5], [100,NaN,0], [1e308,99,0]]) assert.equal(s.budget(...values), null);
assert.deepEqual(s.restore('["a","a","b"]', ['a','b']), ['a','b']);
for (const raw of ['null','{}','bad','["unknown"]','[1]']) assert.deepEqual(s.restore(raw, ['a']), []);
assert.equal(s.answer(2,2), 'correct');
assert.equal(s.answer(2,1), 'review');
for (const selected of [null, undefined, -1, 4, NaN, '2']) assert.equal(s.answer(2, selected), 'unanswered');
console.log('PASS: queue capacity, SLO budget, invalid input, saved-state boundaries and learning-check verdicts.');
